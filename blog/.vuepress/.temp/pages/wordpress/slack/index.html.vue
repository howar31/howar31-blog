<h1 id="slack-簡介" tabindex="-1"><a class="header-anchor" href="#slack-簡介"><span>Slack 簡介</span></a></h1>
<p>Slack 著重於團隊任務溝通，包含許多方便的工具與特色。</p>
<blockquote>
<p><strong>Slack</strong> 官方網站: <a href="http://slack.com/" target="_blank" rel="noopener noreferrer">http://slack.com/</a> 下載網址: <a href="https://slack.com/apps" target="_blank" rel="noopener noreferrer">https://slack.com/apps</a></p>
</blockquote>
<p>Slack 在多種系統上都有對應的程式可用，甚至也有網頁介面，在任何地方都可輕鬆存取，可以依照需求免費安裝或使用對應介面:</p>
<ul>
<li>電腦版
<ul>
<li>Windows</li>
<li>Mac</li>
<li>Linux (Beta)</li>
</ul>
</li>
<li>手機版
<ul>
<li>Android</li>
<li>iOS</li>
<li>Windows Phone (Beta)</li>
</ul>
</li>
<li>網頁版</li>
</ul>
<p>Slack 的架構與傳統一般即時通訊軟體略有不同，他並沒有一個「主帳號」的概念，而是每個平台都有自己獨立的空間，使用者加入一個平台則可在該平台內註冊身份，因此在參與不同團體的 Slack 時都可以有獨立的身份設定等等，不會互相干擾或共用。</p>
<p>每個團隊可以到 Slack 上註冊自己的專屬平台，然後就可以取得團隊專屬的 Slack 網址，所有使用者可以在平台上註冊該平台的帳號密碼，設定該平台專用的名稱、圖片與個人資料，甚至每個平台的設定等等都是獨立分開的。</p>
<h2 id="加入-slack" tabindex="-1"><a class="header-anchor" href="#加入-slack"><span>加入 Slack</span></a></h2>
<p>使用者想加入某個團隊的 Slack ，共有兩種方式:</p>
<ol>
<li>由管理員經由 Email 邀請</li>
<li>管理員設定特定網域 Email 可直接註冊</li>
</ol>
<p>必需要由團隊管理員邀請後才能加入 Slack 平台。Slack 以 Email 為身份辨識，收到邀請的 Email 即可在該團隊的 Slack 進行註冊與設定。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150913_203138_1442147498.png" alt="PicPick_20150913_203138_1442147498"></p>
<p>管理員邀請成員有三種模式:</p>
<ul>
<li>Full Members 一般會員
<ul>
<li>這是一般的會員，可以正常存取所有頻道、檔案與團隊通訊錄</li>
</ul>
</li>
<li>Restricted Accounts 限制會員
<ul>
<li>受限制的會員帳號，只能存取管理員指定的資源</li>
</ul>
</li>
<li>Single-Channel Guests 單頻道客座會員
<ul>
<li>只能進入單一指定頻道的受限制會員</li>
</ul>
</li>
</ul>
<p>這些權限設定之後管理員可以在會員管理裡面更改。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150913_212142_1442150503.png" alt="PicPick_20150913_212142_1442150503"></p>
<p>管理員輸入受邀者的 Email 之後，即可將其邀請入團隊。這裡管理員可以順便設定該使用者的姓名，或是留白讓使用者之後自行設定。此外也可以一次邀請多個 Email ，方便大量邀請。</p>
<p>受邀請的使用者會收到一封 Email :</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150913_222535_1442154336.png" alt="PicPick_20150913_222535_1442154336"></p>
<p>點選信中「Join」按鈕，即可開始註冊帳號。(每個平台帳號獨立，即使之前這個 Email 在其他 Slack 註冊過，仍需要重新註冊此平台專用的帳號資料)</p>
<h2 id="基本功能與特色介紹" tabindex="-1"><a class="header-anchor" href="#基本功能與特色介紹"><span>基本功能與特色介紹</span></a></h2>
<p>Slack 有許多功能，可以讓團隊根據不同的需求，建立專屬的溝通平台，使用者方面也有很多便利的功能，以下將分類介紹常用的功能！</p>
<h3 id="頻道與群組選擇" tabindex="-1"><a class="header-anchor" href="#頻道與群組選擇"><span>頻道與群組選擇</span></a></h3>
<p>Slack 的溝通系統有頻道 (Channel) 、個人訊息 (Direct Message) 和私人群組 (Private Group) 三種類型，可以在選單內看到列表。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_000922_1442160562.png" alt="PicPick_20150914_000922_1442160562"></p>
<h4 id="channels-頻道" tabindex="-1"><a class="header-anchor" href="#channels-頻道"><span>Channels - 頻道</span></a></h4>
<p>與 IRC 等等一般的聊天室一樣， Channels 是公開的聊天頻道，所有人都可以自由預覽、加入與聊天。</p>
<p>頻道可以設定聊天室主題、頻道宗旨等等相關設定，</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_001805_1442161085.png" alt="PicPick_20150914_001805_1442161085"></p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_001749_1442161069.png" alt="PicPick_20150914_001749_1442161069"></p>
<p>聊天室主題會顯示在最上方聊天頻道名稱旁邊，而聊天室主題是顯示在頻道列表中，用於描述頻道用途與說明。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_001939_1442161179.png" alt="PicPick_20150914_001939_1442161179"></p>
<p>頻道的創立、封存與刪除，則要看管理員的權限設定。</p>
<h4 id="direct-messages-個人訊息" tabindex="-1"><a class="header-anchor" href="#direct-messages-個人訊息"><span>Direct Messages - 個人訊息</span></a></h4>
<p>一對一的聊天系統，與傳統的即時通訊類似，使用者對使用者之間的聊天，所有訊息和分享的檔案都只有兩人能看到。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_002842_1442161722.png" alt="PicPick_20150914_002842_1442161722"></p>
<h4 id="private-groups-私人群組" tabindex="-1"><a class="header-anchor" href="#private-groups-私人群組"><span>Private Groups - 私人群組</span></a></h4>
<p>與頻道類似，但為隱藏的私人聊天室，私人群組不會顯示成列表，沒有邀請的使用者甚至不會知道平台上有這些群組，只有被邀請的人才能看到，其餘功能皆與頻道相同。</p>
<p>私人群組的創立、封存、刪除、踢人等管理，也是看團隊管理原是否有開放權限。</p>
<h3 id="聊天對談" tabindex="-1"><a class="header-anchor" href="#聊天對談"><span>聊天對談</span></a></h3>
<p>在 Slack 中的聊天系統，除了一般的聊天以外，還有一些很方便的功能和工具，可以協助團隊進行有效率的溝通，以及提供團隊平台客製化與管理。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_011503_1442164503.png" alt="PicPick_20150914_011503_1442164503"></p>
<h4 id="「-id」標記-和-「-頻道」標記" tabindex="-1"><a class="header-anchor" href="#「-id」標記-和-「-頻道」標記"><span>「@ID」標記 和 「#頻道」標記</span></a></h4>
<p>在聊天中若要提及某個人或是某個頻道，常常會有混淆或是不明顯的問題，例如有 ID 相似的兩個人容易搞混，或是他們沒有注意到聊天室正提到他們，甚至新加入的朋友找不到提及的頻道是哪個。</p>
<p>只要在聊天中使用「@」再加上使用者 ID ，即可標記使用者，被標記的使用者會自動產生超連結，所有人都可以點選該 ID 檢視使用者詳細資料，而被標記的人也會收到通知，並且在聊天文字中高亮顯示。</p>
<p></p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_200123_1442232083.png" alt="PicPick_20150914_200123_1442232083"></p>
<p>而頻道也是相同道理，使用「#」標記頻道，然後就會自動產生超連結，點選該連結就會自動切換到該頻道，十分方便。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_200312_1442232192.png" alt="PicPick_20150914_200312_1442232192"></p>
<h4 id="網址預覽" tabindex="-1"><a class="header-anchor" href="#網址預覽"><span>網址預覽</span></a></h4>
<p>在聊天中輸入網址，Slack 可以自動展開預覽，一般網頁可顯示摘要片段，而圖片或影片網址可直接顯示，並在聊天視窗中直接觀看。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_132044_1442208044.png" alt="PicPick_20150914_132044_1442208044"></p>
<p></p>
<h4 id="檔案分享" tabindex="-1"><a class="header-anchor" href="#檔案分享"><span>檔案分享</span></a></h4>
<p>除了傳統即時通訊軟體一般，可傳送圖片和影片，Slack 還可分享任何格式的檔案。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_193709_1442230629.png" alt="PicPick_20150914_193709_1442230629"></p>
<p>分享的圖片、影片或其他任何檔案，都可以在下面留言，讓討論可以集中，之後察看也比較清楚。、</p>
<p>此外 Slack 可以將頻道上分享的檔案產生公開用的分享網址，讓聊天室以外的人也可以存取檔案，當使用完畢後，也可以手動註銷公開網址。(團隊管理員可關閉此功能)</p>
<h4 id="「星號-star-」和「釘選-pin-」" tabindex="-1"><a class="header-anchor" href="#「星號-star-」和「釘選-pin-」"><span>「星號 (star)」和「釘選 (pin)」</span></a></h4>
<p>這兩個功能屬於書籤功能，可以將重要或有興趣的內容做紀錄儲存，日後需要查找的時候就很方便。</p>
<p>「<strong>星號 (star)</strong>」是個人書籤，使用星號標記自己有興趣的聊天訊息，可以方便以後查閱。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_195356_1442231637.png" alt="PicPick_20150914_195356_1442231637"></p>
<p>「<strong>釘選 (pin)</strong>」為頻道公用的置頂功能，將重要訊息加入頻道的資訊欄位，該頻道內所有人都可以看見。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_201003_1442232604.png" alt="PicPick_20150914_201003_1442232604"></p>
<h4 id="搜尋引擎" tabindex="-1"><a class="header-anchor" href="#搜尋引擎"><span>搜尋引擎</span></a></h4>
<p>Slack 內建十分強大的搜尋引擎，可以搜尋所有聊天紀錄、檔案、成員等等各種資料，並且搭配參數 (modifier) 可以更精確的查找。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_200456_1442232296.png" alt="PicPick_20150914_200456_1442232296"></p>
<p></p>
<h4 id="自訂表情符號" tabindex="-1"><a class="header-anchor" href="#自訂表情符號"><span>自訂表情符號</span></a></h4>
<p>表情符號是聊天室不可或缺的功能， Slack 內建豐富的表情符號，並且可以切換各種風格。 (截圖為 Google Hangouts 風格)</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_201232_1442232753.png" alt="PicPick_20150914_201232_1442232753"></p>
<p>除了內建的表情符號， Slack 更支援自訂表情符號，團隊可以自行定義需要的表情符號，達到更高度客製化的溝通平台！</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_201409_1442232849.png" alt="PicPick_20150914_201409_1442232849"></p>
<h4 id="可針對留言做表情回應-react" tabindex="-1"><a class="header-anchor" href="#可針對留言做表情回應-react"><span>可針對留言做表情回應 (react)</span></a></h4>
<p>表情符號除了在聊天內使用以外，也可以用來針對聊天內容作表情回應。可指定訊息然後選擇表情做回應，除了不會因單行表情佔用聊天版面，也方便統計表情數量，可作為討論事項投票用等等。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_201713_1442233034.png" alt="PicPick_20150914_201713_1442233034"></p>
<p>團隊管理員可以設定權限，決定是否開放讓所有人都能新增或修改團隊的自訂表情。</p>
<h4 id="修改和刪除" tabindex="-1"><a class="header-anchor" href="#修改和刪除"><span>修改和刪除</span></a></h4>
<p>在團隊討論時，常常會有輸入錯誤的問題， Slack 支援訊息修改與刪除。</p>
<p>修改過的訊息會加上小註記註明這是改過的訊息。</p>
<p></p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_202501_1442233502.png" alt="PicPick_20150914_202501_1442233502"></p>
<p></p>
<p>刪除訊息會有提醒視窗，確認是否要刪除。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_202735_1442233656.png" alt="PicPick_20150914_202735_1442233656"></p>
<p>Slack 預設是所有人都能修改和刪除自己的訊息，團隊管理員可以修改權限，限制只有管理員能修改和刪除，也可以設定只有在訊息發佈後的一段時間內才能修改。</p>
<p><img src="@source/wordpress/slack/images/PicPick_20150914_202939_1442233779.png" alt="PicPick_20150914_202939_1442233779"></p>
