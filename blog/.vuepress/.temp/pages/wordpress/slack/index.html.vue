<p>Slack 不但基本功能都免費，且提供完整方便的團隊溝通工具，甚至連美國太空總署 (NASA) 的噴射推進實驗室 (Jet Propulsion Laboratory) 都採用 Slack 進行團隊溝通，證明了 Slack 提供的工具與功能足以協助大型團隊進行互動。</p>
