<p>==</p>
<p><strong><a href="http://http//www.speedtest.net/" target="_blank" rel="noopener noreferrer">SpeedTest</a></strong></p>
<p><a href="http://www.speedtest.net/" target="_blank" rel="noopener noreferrer">SpeedTest</a>是一個能讓你測試你的網路速度的網站，使用者可以選擇世界上各個地點的伺服器做連線測試。</p>
<p>首先進入<a href="http://www.speedtest.net/" target="_blank" rel="noopener noreferrer">SpeedTest</a>網站後，先在左上角找到「Setting」的按鈕，我們要先做一些小小的設定。</p>
<p><img src="http://img249.imageshack.us/img249/5511/mwsnap20100414220946.png" alt="MWSnap 2010-04-14-22-09-46.png"></p>
<p>要設定的部分是「Speed Measurement」和「Distance Measurement」兩個，請把「Speed Measurement」選擇「megabytes」才是我們平常常用的MB/s這個單位，如果是預設的「megabits」則是一般ISP告知使用者的速度單位，例如ISP告訴你你的網路有10M、8M、2M、1M這些，這個「M」就是代表「Megabits」，但是我們平常不用這個單位，所以改成「megabytes」才是慣用的「MB/s」。至於距離單位原本預設是英制的「miles」，如果要選用公制的「公里」請選擇「kilometers」。「Date Format」是指日期的格式，如果有需要的話也可以自行修改。</p>
<p>接下來看到下面的主畫面</p>
<p><img src="http://img249.imageshack.us/img249/2295/mwsnap20100414220924.png" alt="MWSnap 2010-04-14-22-09-24.png"></p>
<p>主畫面左下角顯示你目前網路的IP位置、以及你的ISP名稱。例如筆者的網路是中華電信的，圖中左下角就顯示「CHTD, Chunghwa Telecom......」，你如果有興趣的話下面還可以給你的ISP做評分！接下來看到畫面中間，中間全球地圖上的點表示該地點有測試伺服器，使用者可以選擇任何一個伺服器做連線測試，如果想直接開始測試可以點選上面的「Begin Test」，他會馬上開始測試。</p>
<p>接下來我們實際示範一個例子:</p>
<p>我選擇了台灣的台中伺服器</p>
<p><img src="http://img249.imageshack.us/img249/6573/mwsnap20100414221703.png" alt="MWSnap 2010-04-14-22-17-03.png"></p>
<p>點下去以後他就開始連線台中的伺服器做測試，右邊可以看到台中的伺服器是由東海大學提供的。首先他會測試你的Ping值，這個數值代表網路延遲的時間，單位是毫秒(ms)，數字越低越好。</p>
<p><img src="http://img249.imageshack.us/img249/4333/mwsnap20100414221719.png" alt="MWSnap 2010-04-14-22-17-19.png"></p>
<p>接下來他會測試下載速度，左邊的儀表板顯示下載進度，右邊的儀表板則是目前下載速度。</p>
<p><img src="http://img249.imageshack.us/img249/4402/mwsnap20100414221725.png" alt="MWSnap 2010-04-14-22-17-25.png"></p>
<p>然後測試上傳速度，左邊儀表板同樣顯示上傳進度，右邊是上傳速度。</p>
<p><img src="http://img249.imageshack.us/img249/8513/mwsnap20100414221733.png" alt="MWSnap 2010-04-14-22-17-33.png"></p>
<p>最後結果出來了！</p>
<p><img src="http://img249.imageshack.us/img249/1644/mwsnap20100414221746.png" alt="MWSnap 2010-04-14-22-17-46.png"></p>
<p>測試結果出來，左邊可以看到他幫你估計你下載各種檔案可能需要多久，還有你的網路結果和平均ISP結果的比較，中間可以詳細看到本次測試的上傳、下載速度以及Ping值，還有大家給ISP的平均評分、與測試伺服器大約的地理距離。中間下面還有兩個按鈕，可以把結果的連結複製下來！分為直接連結與論壇格式的連結，方便你把結果分享給別人！😄</p>
<p>筆者的網路是中華電信光纖10M/2M，這個網站顯示結果下載速度是「1.13MB/s」，上傳速度是「0.24MB/s」，與ISP告訴我的差不多！這樣表示網路很正常:D</p>
<p>話說單位換算: 1MB/s = 8 Mb/s，大寫的「MB」表示「MegaBytes」就是我們常用的「MB/s」，小寫的「Mb」表示「Megabits」就是ISP業者告知我們的「10M、8M、2M、1M」這些「M」，所以換算過來下載速度10M的光纖網路 = 1.25MB/s，2M上傳速度 = 0.25MB/s，與我上面測試的結果很接近！表示我的網路能夠發揮極限功效！</p>
<p>[note]</p>
<p>ISP電信業者保證的網路速度只有從「你家」到「他的機房」，所以更遠的連線速度會慢是正常的。</p>
