<p>接下來測試一個叫做「Jitter」的數值，這個數值代表「每次測試結果變動的差異」，例如第一次測試Ping值是17ms，第二次變成21ms，這樣Jitter值就是4ms，因為最大21ms跟17ms差了4ms，所以Jitter值也是越小越好。</p>
