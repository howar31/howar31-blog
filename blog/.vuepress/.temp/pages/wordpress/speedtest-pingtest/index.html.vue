<p><a href="http://www.pingtest.net/" target="_blank" rel="noopener noreferrer"><strong>PingTest</strong></a></p>
<p><a href="http://www.pingtest.net/" target="_blank" rel="noopener noreferrer">PingTest</a>跟<a href="http://www.speedtest.net/" target="_blank" rel="noopener noreferrer">SpeedTest</a>是同一家公司出品的測試網站，不過不同的是<a href="http://www.pingtest.net/" target="_blank" rel="noopener noreferrer">PingTest</a>是測試網路連線的品質而不是頻寬速度。常常打網路遊戲的人應該很瞭解Ping值的重要性，Ping值代表網路延遲的時間，延遲越低越好，越低表示你的網路反應越快！</p>
