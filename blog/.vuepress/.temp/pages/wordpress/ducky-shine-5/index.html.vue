<h1 id="ducky-shine-5-mechanical-keyboard" tabindex="-1"><a class="header-anchor" href="#ducky-shine-5-mechanical-keyboard"><span>Ducky Shine 5 Mechanical Keyboard</span></a></h1>
<p>Ducky Shine 系列最新第 5 代在台灣正式上市，在台灣首發限量一百支特別序號版，九月之後會在澳洲進行國際首發，以及一般版本的上市。</p>
<p>機械鍵盤，雖然早有耳聞，但之前只有簡單接觸過試按一會兒而已，並沒有實際使用，因此原本對機械鍵盤沒有什麼特別興趣。前幾天 (8/19) 一個朋友拿了 Ducky Shine 2 7燈8軸 特別版借我帶回家使用，長時間的常規使用才發現機械鍵盤的魅力。</p>
<p><img src="@source/wordpress/ducky-shine-5/images/P_20150819_202937_1_p.jpg" alt="Ducky Shine 2 78 version"><br>
Ducky Shine 2 78 Version</p>
<p>除了LED燈漂亮之外，最重要的是機械鍵盤按下去的手感果然是非常的舒服，尤其對於長時間使用鍵盤的 coder 來說，舒適度是挺重要的一項考量。</p>
<p>體驗了 Shine 2 78版 之後才真正開始研究機械鍵盤，上網看了很多機械軸和鍵帽的文章，參考一些網友的建議與心得，最後在網友推薦下得知 Ducky Shine 系列即將推出新一代，就在 23 日臨時下定決心加入機械鍵盤行列，很幸運的在硬派精璽訂購到最後一支 Ducky Shine 5 英文茶軸首發版，硬派跟黑貓的效率都很高，在 24 日中午就拿到鍵盤了，首發編號是 <strong>082</strong>/100 。</p>
