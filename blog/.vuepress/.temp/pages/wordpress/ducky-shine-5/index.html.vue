<h1 id="後記感想" tabindex="-1"><a class="header-anchor" href="#後記感想"><span>後記感想</span></a></h1>
<p>其實從來沒想過自己會買機械鍵盤來用，更沒想過第一支機械鍵盤就是 RGB 鍵盤，Ducky Shine 2 7燈8軸 特別版實在太推坑了，一把就可以比較八種軸，還有七色 LED 燈光展示 (雖然單色 LED 和 RGB LED 視覺效果有一點差異) ，剛好又碰上 Shine 5 上市，種種巧合機緣讓我短短五天內就加入機械鍵盤行列。</p>
<p>Ducky Shine 5 目前使用整體感覺良好，機械鍵盤確實不同於薄膜鍵盤，按起來手感真的很舒適，價格在 RGB 機械鍵盤中也挺不錯，加上自家國產 Ducky 廠商，而且全球首發就在台灣，我個人覺得十分超值滿意！</p>
